# -*- coding: utf-8 -*-
"""
前平事業部（事業A）の設計
体制: 前平 ＋ 役員以外から1.5人
目標: 年間売上 1.5億（＝「優秀」ライン）
単位: 万円
"""
# ── 商品（本人申告の実勢価格・粗利率）────────────────────
ITEMS = {
    "理念映像2本パック": (150, 120),   # (単価, 粗利)  粗利率80%
    "理念映像1本":       (100,  80),   # 80%
    "式典 撮影のみ":     ( 15,  13.5), # 90%（編集なし納品）
    "式典 ダイジェスト": ( 20,  18),   # 90%
    "AIリスキリング L":  (120, 108),   # 90%（外注なし）
    "AIリスキリング M":  ( 80,  72),   # 90%
    "AIリスキリング S":  ( 30,  27),   # 90%
}
print("═"*88); print("【商品単価と粗利】"); print("═"*88)
for n,(p,g) in ITEMS.items():
    print(f"  {n:20} 単価 {p:>4}万   粗利 {g:>6.1f}万   粗利率 {g/p*100:>4.0f}%")

# ── 販売パッケージ（1社あたりの組み合わせ）──────────────
def pack(*names):
    p = sum(ITEMS[n][0] for n in names); g = sum(ITEMS[n][1] for n in names)
    return p, g, " ＋ ".join(names)

PACKS = [
    ("① フル",     pack("理念映像2本パック","式典 撮影のみ","式典 ダイジェスト","AIリスキリング L"), 12),
    ("② 映像+研修", pack("理念映像2本パック","AIリスキリング L"),                                     14),
    ("③ 映像+式典", pack("理念映像2本パック","式典 撮影のみ","式典 ダイジェスト"),                     12),
    ("④ 研修L単体", pack("AIリスキリング L"),                                                        14),
    ("⑤ 映像1本",   pack("理念映像1本"),                                                             12),
    ("⑥ 研修M",     pack("AIリスキリング M"),                                                        16),
    ("⑦ 研修S(入口)",pack("AIリスキリング S"),                                                       16),
]
print("\n"+"═"*88); print("【年間の販売ミックス】"); print("═"*88)
print(f"{'':14}{'単価':>7}{'粗利':>8}{'社数':>6}{'売上':>9}{'粗利':>9}  構成")
print("─"*88)
rev=gp=cnt=0
for label,(p,g,desc),n in PACKS:
    rev+=p*n; gp+=g*n; cnt+=n
    print(f"  {label:12}{p:>7}{g:>8.1f}{n:>6}{p*n:>9,}{g*n:>9,.0f}  {desc}")
print("─"*88)
print(f"  {'合計':12}{rev/cnt:>7.0f}{gp/cnt:>8.1f}{cnt:>6}{rev:>9,}{gp:>9,.0f}  粗利率 {gp/rev*100:.0f}%")
print(f"\n  → 年 {cnt}社成約（月 {cnt/12:.1f}社）／ 平均客単価 {rev/cnt:.0f}万")

# ── 前平さんの時間検証 ────────────────────────────────
print("\n"+"═"*88); print("【前平さんの月間稼働】※初回ヒアリング〜成約まで本人"); print("═"*88)
CLOSE = 0.40
deals_m = cnt/12
mtg_m   = deals_m/CLOSE
train_m = (12+14+14+16)/12          # AI研修を含む成約数/月（登壇あり）
ROWS = [("初回ヒアリング商談", mtg_m,      2.5, "本人がやりたいこと"),
        ("提案・成約商談",     deals_m,    2.5, "本人がやりたいこと"),
        ("プランニング（立案）", deals_m,   2.0, "もう1人と分担・清書は0.5人"),
        ("AI研修 初回/最終登壇", train_m*2, 3.0, "本人がやりたいこと"),
        ("経営・セミナー・団体活動", 1,    40.0, "")]
tot=0
for n,c,h,note in ROWS:
    t=c*h; tot+=t
    print(f"  {n:22}{c:>6.1f} × {h:>4.1f}h = {t:>6.1f}h   {note}")
print(f"  {'─'*72}")
print(f"  {'合計':22}{tot:>24.1f}h/月   週 {tot/4.3:.1f}h")
print(f"  判定: {'✓ 成立（余力 %.0fh）'%(180-tot) if tot<=180 else '× 上限180hを %.0fh 超過'%(tot-180)}")

# ── 営業活動量（1.0人が担う）──────────────────────────
print("\n"+"═"*88); print("【営業活動量】月間 %.0f 商談を生むための接触数（1.0人が担当）"%mtg_m); print("═"*88)
CH = [("手紙＋訪問手渡し＋追跡架電", 0.50, 0.08),
      ("電話営業",                  0.30, 0.02),
      ("DM（名刺DB・オプトイン済）", 0.12, 0.03),
      ("ポスティング",              0.08, 0.005)]
for name, share, rate in CH:
    need = mtg_m*share/rate
    print(f"  {name:26} 商談 {mtg_m*share:>4.1f}件 ← 接触 {need:>6.0f}件/月（{need/20:>5.1f}件/日）")
print(f"\n  ⚠ 手紙の訪問手渡しは 1日 {mtg_m*0.5/0.08/20:.0f}社。これに架電と中継対応が乗る。")
print(f"     1.0人では容量オーバーの可能性が高い（訪問だけで1日の半分）。")

# ── 事業部P/L ────────────────────────────────────────
print("\n"+"═"*88); print("【事業部A 単体P/L（年間）】"); print("═"*88)
MAE   = 150*12 + 140 + 170          # 前平 額面150万×12＋賞与140＋法定福利
STAFF = 60*12*1.5*1.15              # 1.5人 額面60万（手取り2倍）＋法定福利
DIRECT= (3+10+30+5+10)*12           # 手紙印刷郵送3/ポスティング10/広告30/交通5/ツール10
print(f"  売上                       {rev:>8,}万")
print(f"  原価（外注）               {rev-gp:>8,.0f}万   粗利率 {gp/rev*100:.0f}%")
print(f"  粗利                       {gp:>8,.0f}万")
print(f"  ─────────────────────────────────────")
print(f"  前平（役員報酬・賞与・社保） {MAE:>8,}万")
print(f"  1.5人（額面60万・手取り2倍）{STAFF:>8,.0f}万")
print(f"  事業部の直接経費           {DIRECT:>8,}万   広告360/ポスティング120/ツール120/郵送36/交通60")
print(f"  ─────────────────────────────────────")
print(f"  事業部の貢献利益           {gp-MAE-STAFF-DIRECT:>8,.0f}万   ← 全社の共通費と他役員2名を賄う原資")

# ═══════════════════════════════════════════════════════════
# 全社ロールアップ（事業A ＋ 事業B）
# ═══════════════════════════════════════════════════════════
B_REV, B_GPR = 10000, 0.48          # 事業B 代理店TVCM（据え置き・粗利率48%）
EXEC3   = 6331                       # 役員3名 額面150万×12＋賞与140＋法定福利
STAFF5  = 60*12*5*1.15               # 一般社員5名 額面60万（手取り2倍）＋法定福利
COMMON  = 135.5*12                   # 全社共通経費（DB実測 月135.5万）
RESERVE = (34+20)*12                  # ボーナス積立34万＋チャレンジ枠20万（月）
LOAN    = 29.539*12                   # 借入返済 月29.5万（税引後利益から）
TAX     = 0.34

def rollup(a_rev, a_gpr=0.85, label=""):
    rev = a_rev + B_REV
    gp  = a_rev*a_gpr + B_REV*B_GPR
    cost= EXEC3 + STAFF5 + DIRECT + COMMON + RESERVE
    op  = gp - cost
    at  = op*(1-TAX)
    return dict(label=label, rev=rev, gp=gp, gpr=gp/rev*100, cost=cost, op=op, at=at, after_loan=at-LOAN)

print("\n"+"═"*92)
print("【全社ロールアップ】事業A ＋ 事業B（代理店1億・据え置き）")
print("═"*92)
print(f"  固定費: 役員3名 {EXEC3:,}／一般5名 {STAFF5:,.0f}／事業A直接 {DIRECT:,}／"
      f"全社共通 {COMMON:,.0f}／積立利益枠 {RESERVE:,}  = {EXEC3+STAFF5+DIRECT+COMMON+RESERVE:,.0f}万")
print()
print(f"{'事業A売上':>10}{'全社売上':>10}{'粗利':>9}{'粗利率':>7}{'営業利益':>9}{'税引後':>9}{'返済後':>9}  判定")
print("─"*92)
for a in (10000, 12000, 14300, 15000, 17900, 30000):
    r = rollup(a)
    j = []
    if r['at']    >= 2000: j.append("税引後2000万✓")
    if r['gp']    >=20000: j.append("粗利2億✓")
    if r['rev']   >=40000: j.append("売上4億✓")
    print(f"{a:>10,}{r['rev']:>10,}{r['gp']:>9,.0f}{r['gpr']:>6.0f}%{r['op']:>9,.0f}"
          f"{r['at']:>9,.0f}{r['after_loan']:>9,.0f}  {' '.join(j) if j else '—'}")

print("\n"+"═"*92)
print("【憲法の3つの目標に必要な事業A売上】")
print("═"*92)
need_at = (2000/(1-TAX) + EXEC3+STAFF5+DIRECT+COMMON+RESERVE - B_REV*B_GPR)/0.85
need_at_loan = ((2000+LOAN)/(1-TAX) + EXEC3+STAFF5+DIRECT+COMMON+RESERVE - B_REV*B_GPR)/0.85
need_gp = (20000 - B_REV*B_GPR)/0.85
need_rev= 40000 - B_REV
for lbl, a in [("税引後2,000万を残す",need_at), ("税引後2,000万＋借入返済",need_at_loan),
               ("粗利2億",need_gp), ("売上4億",need_rev)]:
    print(f"  {lbl:26} 事業A {a:>7,.0f}万（{a/10000:.2f}億）  全社 {(a+B_REV)/10000:.2f}億"
          f"   {'← 前平さんの「1.5億で優秀」とほぼ一致' if abs(a-15000)<2000 else ''}")
