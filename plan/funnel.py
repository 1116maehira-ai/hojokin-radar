# -*- coding: utf-8 -*-
"""営業ファネル・体制・社長の時間の逆算（model.py と前提を揃えること）"""
Q      = ["Q1","Q2","Q3","Q4","Q5","Q6"]
PERIOD = ["2026/09-11","2026/12-2027/02","2027/03-05","2027/06-08","2027/09-11","2027/12-2028/02"]
DEALS  = [5, 9, 14, 19, 21, 22]     # 四半期の直請け成約件数（model.py の UNITS 合計）

CLOSE       = 0.40   # 商談 → 成約
SEM_Q       = [1, 2, 3, 3, 4, 4]    # セミナー開催回数/四半期
SEM_GUEST   = 20     # 1回の参加社数
SEM_TO_MTG  = 0.30   # 参加 → 商談
LETTER_RATE = 0.08   # 手紙＋訪問手渡し＋追跡架電 → 商談
COLD_RATE   = 0.02   # 架電・DM単独 → 商談
LETTER_MIX  = 0.60   # アウトバウンドのうち手紙ルートで取る割合

print("═"*100)
print("営業ファネル 逆算")
print("═"*100)
print(f"{'Q':4}{'期間':18}{'成約':>6}{'商談':>7}{'ｾﾐﾅｰ経由':>10}{'ｱｳﾄ':>7}"
      f"{'手紙/月':>9}{'架電/月':>9}{'接触/月':>9}{'商談/月':>9}")
print("─"*100)
for i in range(6):
    mtg  = DEALS[i]/CLOSE
    sem  = SEM_Q[i]*SEM_GUEST*SEM_TO_MTG
    out  = max(mtg-sem, 0)
    ltr  = (out*LETTER_MIX)/LETTER_RATE/3
    cld  = (out*(1-LETTER_MIX))/COLD_RATE/3
    print(f"{Q[i]:4}{PERIOD[i]:18}{DEALS[i]:6}{mtg:7.0f}{sem:10.0f}{out:7.0f}"
          f"{ltr:9.0f}{cld:9.0f}{ltr+cld:9.0f}{mtg/3:9.1f}")

print("\n"+"═"*100)
print("社長の月間時間配分（Q6＝目標水準）")
print("═"*100)
mtg_m = 22/3/CLOSE                      # 月間の初回商談数
ITEMS = [("初回ヒアリング商談",        mtg_m,        2.5),
         ("立案・提案商談",            mtg_m*0.7,    2.5),
         ("プランニング・提案書作成",   mtg_m*0.7,    3.0),
         ("AI研修 初回・最終登壇",      (6+3)/3*2,   3.0),
         ("セミナー登壇＋準備",         4/3,          6.0),
         ("経営・採用・数値管理",       1,           25.0),
         ("団体活動・会食（関係構築）",  8,            2.5)]
tot = 0
for n,c,h in ITEMS:
    t = c*h; tot += t
    print(f"  {n:26}{c:6.1f}件 × {h:4.1f}h = {t:6.1f}h")
print(f"  {'─'*54}")
print(f"  {'合計':26}{tot:26.1f}h/月   週 {tot/4.3:.1f}h")
print(f"\n  ⚠ 稼働可能を月180h（週42h）とすると余力 {180-tot:.1f}h。"
      f"{'限界' if tot>160 else '余力あり'}")
print(f"  → 初回商談を社長が全件担当できる上限は 月 {(180-(tot-mtg_m*2.5))/2.5:.0f}件"
      f"（計画は月 {mtg_m:.0f}件）")

print("\n"+"═"*100)
print("体制 社内10名（2028/03 達成後・人件費 月600万）")
print("═"*100)
TEAM = [("代表",                    1, "ヒアリング・立案・商談・成約・初回/最終登壇", "―"),
        ("インサイドセールス",       2, "架電・DM手配・折込手配・SNS運用・リスト整備",  "Q1/Q4"),
        ("フロント営業",             2, "手紙の訪問手渡し・追跡・関係維持",           "Q2/Q5"),
        ("ディレクター（映像PM）",    2, "コンテ・品質管理・進行・外注統括",           "Q2/Q4"),
        ("AI事業マネージャー",        1, "研修設計・講師統括・教材カスタマイズ",        "Q2"),
        ("AI運用パートナー",         1, "ストック顧客の月次伴走・新規業務のAI化",       "Q3"),
        ("バックオフィス",           1, "経理・請求・助成金事務・契約",               "Q3")]
print(f"{'役割':22}{'人数':>4}  {'投入':10}{'担当'}")
print("─"*100)
for r,n,d,w in TEAM:
    print(f"{r:22}{n:>4}  {w:10}{d}")
HEAD = sum(n for _,n,_,_ in TEAM)
print(f"{'─'*100}")
print(f"  社内 {HEAD}名 / 人件費 月600万 → 平均額面 {600/HEAD:.0f}万")
print(f"  代表150万を除くと {HEAD-1}名で450万 → 平均額面 {450/(HEAD-1):.0f}万（手取り約{450/(HEAD-1)*0.78:.0f}万）")
print(f"  ※ 映像チーム・AI中継講師・デザイナーは外注（原価側・売上の35〜50%）")

print("\n"+"═"*100)
print("社長の時間 ─ 対策後（ボトルネック解消案）")
print("═"*100)
FIX = [("初回ヒアリング商談",       mtg_m,      2.5, "維持（やりたいこと）"),
       ("立案・提案商談",           mtg_m*0.7,  2.5, "維持（やりたいこと）"),
       ("立案の口述＋赤入れ",        mtg_m*0.7,  1.0, "提案書の清書はAIとﾃﾞｨﾚｸﾀｰへ ▲2.0h"),
       ("AI研修 初回・最終登壇",     6.0,        3.0, "維持（やりたいこと）"),
       ("セミナー登壇＋準備",        4/3,        4.0, "準備は講師陣へ ▲2.0h"),
       ("経営・採用・数値管理",      1,         20.0, "ダッシュボード自動化 ▲5.0h"),
       ("団体活動・会食",           5,          2.5, "8件→5件に厳選 ▲7.5h")]
tot2 = 0
for n,c,h,note in FIX:
    t=c*h; tot2+=t
    print(f"  {n:22}{c:6.1f} × {h:4.1f}h = {t:6.1f}h   {note}")
print(f"  {'─'*82}")
print(f"  {'合計':22}{tot2:22.1f}h/月   週 {tot2/4.3:.1f}h   （対策前 {tot:.1f}h から ▲{tot-tot2:.1f}h）")
print(f"  {'判定':22}{'✓ 成立（余力 %.1fh）'%(180-tot2) if tot2<=180 else '× 未解決'}")
print("""
  ▸ 最大の削減は「提案書の清書」38.5h → 12.8h。
    立案は社長、清書はAI＋ディレクター。
    これは ビジョン2年「考えない作業みたいな仕事は誰もやってない」の自社への適用そのもの。
""")
